#!/usr/bin/env node

/**
 * AQLIYA Authority Matrix Generator
 *
 * Reads the generated knowledge-map.json and produces a markdown
 * authority matrix: docs/DOCUMENTATION_AUTHORITY_MATRIX.md
 *
 * Usage:
 *   node scripts/generate-authority-matrix.mjs
 *
 * Output: docs/DOCUMENTATION_AUTHORITY_MATRIX.md
 */

import { readFileSync, existsSync, writeFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(__dirname, '..');
const KM_PATH = resolve(REPO_ROOT, 'docs/ai/knowledge-map.json');
const OUTPUT = resolve(REPO_ROOT, 'docs/DOCUMENTATION_AUTHORITY_MATRIX.md');

console.log('\n🔍 AQLIYA Authority Matrix Generator\n');

// Load knowledge map
let km;
try {
  km = JSON.parse(readFileSync(KM_PATH, 'utf-8'));
} catch (e) {
  console.error(`Cannot read knowledge-map.json: ${e.message}`);
  console.log('Run `node scripts/generate-knowledge-map.mjs` first.');
  process.exit(1);
}

console.log('Loaded knowledge-map.json');

// Priority descriptions
const PRIORITY_DESC = {
  'P0-critical': 'Critical — must read every session',
  'P1-high': 'High — must read before relevant work',
  'P1-essential': 'Essential — core reference',
  'P2-medium': 'Medium — read when needed',
  'P2-supplemental': 'Supplemental — context when relevant',
  'P3-low': 'Low — occasional reference',
  'P4-archive': 'Archive — historical only',
  'P999': 'Archived/Deprecated',
};

// Section descriptions
const SECTION_DESC = {
  critical: 'Critical — must read every session',
  high_priority: 'High Priority — essential reference',
  architecture: 'Architecture & Design',
  product: 'Product Documentation',
  security: 'Security & Compliance',
  deployment: 'Deployment & Infrastructure',
  governance: 'Governance & Policy',
  operations: 'Operations & Monitoring',
  roadmaps: 'Roadmaps & Strategy',
  archive: 'Archive (historical only)',
  deprecated: 'Deprecated (do not use)',
  superseded: 'Superseded (use replacement)',
};

// Build the markdown
const lines = [];
lines.push('# AQLIYA Documentation Authority Matrix');
lines.push('');
lines.push('> **Auto-generated** from `docs/ai/knowledge-map.json`.');
lines.push('> Last generated: ' + new Date().toISOString().split('T')[0]);
lines.push('');
lines.push('This matrix lists every document in the AQLIYA documentation system with its authority level,');
lines.push('priority, owner, and dependencies. Use this table to determine which documents to read');
lines.push('and in which order.');
lines.push('');

// Overview table
lines.push('## Overview');
lines.push('');
lines.push('| Section | Count | Description |');
lines.push('|---------|-------|-------------|');

const groups = Object.keys(km).filter(k => !k.startsWith('$'));
const total = groups.reduce((sum, g) => sum + (Array.isArray(km[g]) ? km[g].length : 0), 0);

for (const group of groups) {
  const count = Array.isArray(km[group]) ? km[group].length : 0;
  const desc = SECTION_DESC[group] || group;
  lines.push(`| ${capitalize(group)} | ${count} | ${desc} |`);
}
lines.push(`| **Total** | **${total}** | |`);
lines.push('');

// Priority legend
lines.push('## Priority Legend');
lines.push('');
lines.push('| Label | Description |');
lines.push('|-------|-------------|');
for (const [prio, desc] of Object.entries(PRIORITY_DESC)) {
  lines.push(`| ${prio} | ${desc} |`);
}
lines.push('');

// Generate group sections
const groupOrder = ['critical', 'high_priority', 'architecture', 'product', 'security', 'deployment', 'governance', 'operations', 'roadmaps', 'archive', 'deprecated', 'superseded'];

for (const group of groupOrder) {
  const entries = Array.isArray(km[group]) ? km[group] : [];
  if (entries.length === 0) continue;

  lines.push(`## ${capitalize(group)}`);
  lines.push('');
  lines.push(SECTION_DESC[group] || '');
  lines.push('');
  lines.push('| Document | Priority | Owner | Status | Dependencies |');
  lines.push('|----------|----------|-------|--------|--------------|');

  for (const entry of entries) {
    const path = entry.path || '';
    const docName = path.split('/').pop() || path;
    const priority = entry.priority || 'P2-medium';
    const owner = entry.owner || 'Unassigned';
    const status = entry.status || 'active';
    const deps = Array.isArray(entry.dependsOn) ? entry.dependsOn.join(', ') : (entry.dependsOn || 'none');

    lines.push(`| \`${path}\` | ${priority} | ${owner} | ${status} | ${deps} |`);
  }
  lines.push('');
}

// Footer
lines.push('---');
lines.push('');
lines.push('_Generated by `scripts/generate-authority-matrix.mjs` from `docs/ai/knowledge-map.json`._');

const output = lines.join('\n');

// Write
writeFileSync(OUTPUT, output, 'utf-8');
console.log(`✅ Written to ${OUTPUT.replace(REPO_ROOT, '').replace(/\\/g, '/')} (${total} entries, ${groups.length} groups)\n`);

function capitalize(str) {
  return str.charAt(0).toUpperCase() + str.slice(1).replace(/_/g, ' ');
}
